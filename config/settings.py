def load_optional_secret(name, default=""):
    from_env = os.environ.get(name)
    if from_env is not None and str(from_env).strip():
        return str(from_env).strip()

    # 디버그 모드에서는 secrets.json 파일이 없어도 기본값 반환
    if DEBUG:
        return default

    secrets_path = BASE_DIR / "config" / "secrets.json"
    if secrets_path.exists():
        try:
            with secrets_path.open("r", encoding="utf-8") as file:
                secrets = json.load(file)
        except (OSError, json.JSONDecodeError):
            return default
        value = secrets.get(name)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return default


def load_optional_int_secret(name, default):
    from_env = os.environ.get(name)
    if from_env is not None and str(from_env).strip():
        try:
            return int(str(from_env).strip())
        except ValueError:
            return default

    if DEBUG:
        return default

    secrets_path = BASE_DIR / "config" / "secrets.json"
    if secrets_path.exists():
        try:
            with secrets_path.open("r", encoding="utf-8") as file:
                secrets = json.load(file)
        except (OSError, json.JSONDecodeError):
            return default
        value = secrets.get(name)
        try:
            return int(value)
        except (TypeError, ValueError):
            return default
    return default


def load_optional_bool_secret(name, default=False):
    from_env = os.environ.get(name)
    if from_env is not None and str(from_env).strip():
        return str(from_env).strip().lower() in {"1", "true", "yes", "on"}

    if DEBUG:
        return default

    secrets_path = BASE_DIR / "config" / "secrets.json"
    if secrets_path.exists():
        try:
            with secrets_path.open("r", encoding="utf-8") as file:
                secrets = json.load(file)
        except (OSError, json.JSONDecodeError):
            return default
        value = secrets.get(name)
        if isinstance(value, bool):
            return value
        if isinstance(value, str) and value.strip():
            return value.strip().lower() in {"1", "true", "yes", "on"}
    return default

